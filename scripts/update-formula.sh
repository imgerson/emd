#!/usr/bin/env bash
# Update the Homebrew formula in imgerson/homebrew-emd for a published release.
# Usage: scripts/update-formula.sh v0.1.0   (needs gh, authenticated; run from anywhere)
set -euo pipefail
tag=${1:?usage: update-formula.sh vX.Y.Z}
ver=${tag#v}
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

gh release download "$tag" -R imgerson/emd -p SHA256SUMS -D "$work"
sum() { awk -v f="emd_${ver}_$1.tar.gz" '$2 == f { print $1 }' "$work/SHA256SUMS"; }
url="https://github.com/imgerson/emd/releases/download/$tag"

gh repo clone imgerson/homebrew-emd "$work/tap" -- -q
mkdir -p "$work/tap/Formula"
cat > "$work/tap/Formula/emd.rb" <<RUBY
# Generated by imgerson/emd scripts/update-formula.sh. Don't edit by hand.
class Emd < Formula
  desc "Command-line client for easymarkdown (easymarkdown.io)"
  homepage "https://easymarkdown.io/docs/api"
  version "$ver"

  on_macos do
    on_arm do
      url "$url/emd_${ver}_darwin_arm64.tar.gz"
      sha256 "$(sum darwin_arm64)"
    end
    on_intel do
      url "$url/emd_${ver}_darwin_amd64.tar.gz"
      sha256 "$(sum darwin_amd64)"
    end
  end

  on_linux do
    on_arm do
      url "$url/emd_${ver}_linux_arm64.tar.gz"
      sha256 "$(sum linux_arm64)"
    end
    on_intel do
      url "$url/emd_${ver}_linux_amd64.tar.gz"
      sha256 "$(sum linux_amd64)"
    end
  end

  def install
    bin.install "emd"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/emd version")
  end
end
RUBY

cd "$work/tap"
git add Formula/emd.rb
git commit -qm "emd $ver"
git push -q origin HEAD
echo "Formula updated to $ver"
